    <div class="rounded-xl border border-zinc-200 bg-zinc-50 p-4 dark:border-zinc-800 dark:bg-zinc-900/50 space-y-2 text-xs">
        <p>
            <strong>FORNUVI S.A.S.</strong>, sociedad comercial legalmente constituida bajo las leyes de la República de Colombia, identificada con NIT 901.953.881-1, con domicilio principal en la ciudad de Cali (en adelante, “LA COMPAÑÍA”).
        </p>
        <p>
            Y: La persona natural o jurídica que acepta los términos del presente documento de manera electrónica mediante la marcación de la casilla de aceptación (en adelante, “EL DISTRIBUIDOR INDEPENDIENTE”).
        </p>
        <p>
            Ambas partes, denominadas conjuntamente como “LAS PARTES”, han acordado celebrar el presente Contrato de Vinculación Comercial, el cual se regirá por la legislación colombiana, en especial la Ley 1700 de 2013, y por las siguientes cláusulas:
        </p>
    </div>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            DECLARACIONES
        </h3>
        <p>
            <strong>LA COMPAÑÍA</strong> declara que su objeto social principal consiste en la estructuración, desarrollo y operación de un sistema de comercialización en red o marketing multinivel, conforme a la Ley 1700 de 2013. Dicha actividad se materializa a través de una plataforma que integra un portafolio de oportunidades comerciales para sus Distribuidores Independientes, el cual podrá incluir, de manera no limitativa, las siguientes modalidades:
        </p>
        <ul class="list-disc pl-5 space-y-1.5 marker:text-primary dark:marker:text-zinc-400">
            <li><strong>Intermediación Comercial:</strong> La operación de una plataforma de comercio electrónico para la venta de productos suministrados por LA COMPAÑÍA o por terceros proveedores.</li>
            <li><strong>Programa de Referidos con Aliados:</strong> La gestión de un programa de beneficios y compensaciones basado en alianzas estratégicas con establecimientos de comercio externos, mediante el cual se generan ingresos derivados del consumo realizado por la red en dichos establecimientos.</li>
            <li><strong>Distribución de Productos Propios:</strong> Eventualmente, la distribución y venta directa de productos desarrollados o marcados por LA COMPAÑÍA.</li>
        </ul>
        <p class="mt-2">
            <strong>EL DISTRIBUIDOR INDEPENDIENTE</strong> declara ser mayor de edad, con plena capacidad legal para contratar y obligarse, y manifiesta su interés voluntario de vincularse a la red comercial de LA COMPAÑÍA bajo la modalidad de Distribuidor Independiente.
        </p>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA PRIMERA: OBJETO DEL CONTRATO
        </h3>
        <p>
            El objeto de este contrato es establecer los términos y condiciones que regulan la relación comercial, de carácter mercantil e independiente, entre LA COMPAÑÍA y EL DISTRIBUIDOR INDEPENDIENTE. En virtud de esta relación, EL DISTRIBUIDOR INDEPENDIENTE promoverá y comercializará los productos y/o servicios ofrecidos en la plataforma de LA COMPAÑÍA, y podrá desarrollar una red de distribución, a cambio de las compensaciones económicas establecidas en el Plan de Compensación vigente.
        </p>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA SEGUNDA: ACEPTACIÓN Y PERFECCIONAMIENTO
        </h3>
        <p>
            EL DISTRIBUIDOR INDEPENDIENTE manifiesta que, al marcar la casilla <em>"☑️ He leído y acepto los Términos y Condiciones y el Contrato de Afiliación como Distribuidor Independiente de Fornuvi S.A.S, el cual he leído previamente y entiendo en su totalidad"</em>, está firmando y aceptando de manera libre, expresa e inequívoca el contenido íntegro de este contrato, el cual adquiere plena validez y fuerza vinculante entre LAS PARTES.
        </p>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA TERCERA: NATURALEZA DE LA RELACIÓN
        </h3>
        <p>
            LAS PARTES acuerdan y reconocen que la relación que surge de este contrato es de naturaleza estrictamente mercantil y autónoma. En consecuencia:
        </p>
        <ul class="list-disc pl-5 space-y-1.5 marker:text-primary dark:marker:text-zinc-400">
            <li><strong>No existe relación laboral:</strong> Este contrato no crea, ni se interpretará como creador de, una relación laboral, contrato de trabajo, sociedad o empresa conjunta entre LA COMPAÑÍA y EL DISTRIBUIDOR INDEPENDIENTE.</li>
            <li><strong>Independencia y Autonomía:</strong> EL DISTRIBUIDOR INDEPENDIENTE no estará sujeto a subordinación, no cumplirá un horario de trabajo impuesto por LA COMPAÑÍA, y desarrollará su actividad con sus propios medios, bajo su propio riesgo y autonomía.</li>
            <li><strong>Responsabilidades Tributarias y de Seguridad Social:</strong> EL DISTRIBUIDOR INDEPENDIENTE es el único responsable de la declaración y pago de todos sus impuestos (IVA, Renta, Retención en la Fuente, etc.), así como de sus afiliaciones y cotizaciones al Sistema de Seguridad Social Integral (salud, pensión y riesgos laborales) como trabajador independiente, conforme a la ley colombiana.</li>
        </ul>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA CUARTA: REQUISITOS DE VINCULACIÓN
        </h3>
        <p>Para ser y permanecer como DISTRIBUIDOR INDEPENDIENTE, se deberá cumplir con lo siguiente:</p>
        <ul class="list-disc pl-5 space-y-1 marker:text-primary dark:marker:text-zinc-400">
            <li>Ser mayor de edad y residente legal en Colombia.</li>
            <li>Suministrar información personal veraz, completa y actualizada durante el registro y mantenerla así durante la vigencia del contrato.</li>
            <li>No haber sido suspendido o terminado de forma definitiva de la red de LA COMPAÑÍA por incumplimiento grave de sus políticas.</li>
            <li>Aceptar este contrato y cumplir con todas las políticas, códigos de ética y manuales emitidos por LA COMPAÑÍA.</li>
        </ul>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA QUINTA: DERECHOS DEL DISTRIBUIDOR INDEPENDIENTE
        </h3>
        <p>EL DISTRIBUIDOR INDEPENDIENTE tendrá derecho a:</p>
        <ul class="list-disc pl-5 space-y-1.5 marker:text-primary dark:marker:text-zinc-400">
            <li>Recibir las compensaciones económicas (comisiones, bonos, incentivos) de acuerdo con lo estipulado en el Plan de Compensación vigente.</li>
            <li>Acceder a capacitaciones, material de apoyo, herramientas digitales y soporte proporcionado por LA COMPAÑÍA.</li>
            <li>Adquirir los productos ofrecidos por LA COMPAÑÍA.</li>
            <li>Terminar unilateralmente y en cualquier momento el presente contrato, mediante notificación escrita a LA COMPAÑÍA, sin que ello genere penalización alguna.</li>
        </ul>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA SEXTA: OBLIGACIONES DEL DISTRIBUIDOR INDEPENDIENTE
        </h3>
        <p>EL DISTRIBUIDOR INDEPENDIENTE se obliga a:</p>
        <ul class="list-disc pl-5 space-y-1.5 marker:text-primary dark:marker:text-zinc-400">
            <li>Actuar siempre con ética, honestidad, transparencia y profesionalismo, protegiendo la reputación de LA COMPAÑÍA.</li>
            <li>Promover y vender los productos basándose en sus características y beneficios reales, sin incurrir en publicidad engañosa, exageraciones o promesas de ganancias garantizadas.</li>
            <li>Cumplir estrictamente con el Plan de Compensación, el Código de Ética y demás políticas internas de LA COMPAÑÍA.</li>
            <li>No utilizar las marcas, logos y nombres comerciales de LA COMPAÑÍA para fines distintos a los autorizados en este contrato.</li>
            <li>Mantener la confidencialidad sobre la información privilegiada de LA COMPAÑÍA a la que tenga acceso.</li>
        </ul>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA SÉPTIMA: PLAN DE COMPENSACIÓN
        </h3>
        <p>
            El Plan de Compensación de LA COMPAÑÍA es un documento anexo que forma parte integral de este contrato. Dicho plan detalla la estructura de ingresos, los requisitos para calificar a los distintos rangos y las formas de pago.
        </p>
        <p>
            Se deja constancia expresa que las compensaciones se derivan principalmente de la venta de productos y/o servicios a consumidores finales, ya sea directamente o a través de su red de distribución, y no del mero hecho de reclutar a otras personas. LA COMPAÑÍA mantendrá el Plan de Compensación actualizado y accesible para consulta a través de la página oficial de Fornuvi.
        </p>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA OCTAVA: POLÍTICA DE DEVOLUCIÓN Y GARANTÍA
        </h3>
        <p>
            Esta política regula las transacciones de productos y/o servicios adquiridos directamente desde la tienda virtual o plataforma de LA COMPAÑÍA:
        </p>
        <ul class="list-disc pl-5 space-y-2 marker:text-primary dark:marker:text-zinc-400">
            <li>
                <strong>Exclusión de Transacciones con Comercios Aliados:</strong> Se deja constancia expresa de que LA COMPAÑÍA actúa como un simple intermediario en las transacciones que EL DISTRIBUIDOR INDEPENDIENTE o su red realicen en los establecimientos de comercios aliados. Por lo tanto, cualquier reclamación sobre productos o servicios de comercios aliados deberá ser gestionada directamente ante el comercio tercero.
            </li>
            <li>
                <strong>Derecho de Retracto (Compras en la Plataforma Fornuvi):</strong> Conforme al artículo 47 de la Ley 1480 de 2011, EL DISTRIBUIDOR INDEPENDIENTE podrá ejercer el derecho de retracto sobre los productos adquiridos directamente de LA COMPAÑÍA dentro de los cinco (5) días hábiles siguientes a la entrega del producto.
            </li>
            <li>
                <strong>Garantía de Recompra (Terminación del Contrato):</strong> En estricto cumplimiento con la Ley 1700 de 2013, LA COMPAÑÍA recomprará los productos no perecederos que el Distribuidor Independiente haya adquirido directamente de LA COMPAÑÍA y que aún se encuentren en su poder, en perfecto estado, sellados y con fecha de expiración vigente, dentro de los seis (6) meses previos a la terminación, reembolsando un mínimo del noventa por ciento (90%) del costo neto original pagado.
            </li>
        </ul>
    </section>

    <section class="space-y-2">
        <h3 class="text-base font-bold text-ink dark:text-zinc-100">
            CLÁUSULA NOVENA: DURACIÓN Y TERMINACIÓN
        </h3>
        <p>
            <strong>Duración:</strong> El presente contrato es de término indefinido y estará vigente mientras LAS PARTES cumplan con sus obligaciones.
        </p>
        <p>
            <strong>Terminación por parte del Distribuidor:</strong> Podrá darlo por terminado en cualquier momento, sin necesidad de justificar la causa, mediante notificación escrita enviada al correo electrónico oficial.
        </p>
        <p>
            <strong>Terminación por parte de LA COMPAÑÍA:</strong> De forma inmediata en caso de incumplimiento grave de las cláusulas, actos fraudulentos o inactividad prolongada según las políticas internas.
        </p>
    </section>

